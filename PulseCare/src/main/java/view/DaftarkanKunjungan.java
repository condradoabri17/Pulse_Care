        private void muatPoliklinik() {
        daftarPoli.clear();
        jComboBox1.removeAllItems();

        String sql = "SELECT id_poli, nama_poli FROM poliklinik "
                   + "ORDER BY nama_poli";

        try (Connection conn = KoneksiDB.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {

            while (rs.next()) {
                String idPoli = rs.getString("id_poli");
                String namaPoli = rs.getString("nama_poli");

                daftarPoli.put(namaPoli, idPoli);
                jComboBox1.addItem(namaPoli);
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Gagal memuat poliklinik: " + e.getMessage());
        }
    }
